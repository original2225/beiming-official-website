/**
 * 把 ApiError 翻译成可以放到界面上的文案。
 * 未收录的错误码退化为「后端原文（错误码 N）」，保证一定给出可追踪的线索。
 */
export function describeApiError(code: number, message?: string): string {
  const known = MESSAGES[code]
  if (known) return known
  if (code === 0) {
    // code 0 是本模块内部合成的错误（网络失败、响应体异常），message 已经写好中文
    return message || '请求失败，请稍后重试'
  }
  const raw = (message || '').trim()
  return raw ? `${raw}（错误码 ${code}）` : `请求失败（错误码 ${code}）`
}